import { readFileSync, writeFileSync } from "node:fs";
import { isAllowed } from "./license-policy.ts";

type LockEntry = { version?: string; license?: string; link?: boolean; dev?: boolean };
type Lockfile = { packages: Record<string, LockEntry> };
export type PackageLicense = { name: string; version: string; license: string; dev: boolean };

const reportPath = "docs/LICENSES.md";

/** Lists every installed third-party package recorded in the lockfile. */
export function collectLicenses(lock: Lockfile): PackageLicense[] {
  const result = new Map<string, PackageLicense>();
  for (const [path, entry] of Object.entries(lock.packages)) {
    const marker = path.lastIndexOf("node_modules/");
    if (marker === -1 || entry.link) continue;
    const name = path.slice(marker + "node_modules/".length);
    const version = entry.version ?? "unknown";
    const license = entry.license ?? "UNKNOWN";
    result.set(`${name}@${version}`, { name, version, license, dev: entry.dev === true });
  }
  return [...result.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/** Renders the licence report grouped by licence expression. */
export function renderReport(packages: PackageLicense[]): string {
  const groups = new Map<string, string[]>();
  for (const pkg of packages) {
    const list = groups.get(pkg.license) ?? [];
    list.push(`${pkg.name}@${pkg.version}${pkg.dev ? " (dev)" : ""}`);
    groups.set(pkg.license, list);
  }
  const lines = [
    "# Licence report",
    "",
    "Generated by `npm run licenses` from package-lock.json. Do not edit by hand.",
    "",
    `Packages audited: ${String(packages.length)}, direct and indirect, all platforms.`,
    "",
    "| Licence | Allowed | Count |",
    "| --- | --- | --- |",
  ];
  const sorted = [...groups.entries()].sort((a, b) => b[1].length - a[1].length);
  for (const [license, list] of sorted) {
    lines.push(`| ${license} | ${isAllowed(license) ? "yes" : "NO"} | ${String(list.length)} |`);
  }
  lines.push("", "## Packages by licence", "");
  for (const [license, list] of sorted) lines.push(`- **${license}**: ${list.join(", ")}`);
  return `${lines.join("\n")}\n`;
}

/** Audits the lockfile; writes the report or fails when it is stale. */
export function auditLicenses(write: boolean): string[] {
  const lock = JSON.parse(readFileSync("package-lock.json", "utf8")) as Lockfile;
  const packages = collectLicenses(lock);
  const report = renderReport(packages);
  const errors = packages
    .filter((pkg) => !isAllowed(pkg.license))
    .map((pkg) => `Denied licence: ${pkg.name}@${pkg.version} ${pkg.license}`);
  if (write) writeFileSync(reportPath, report);
  else if (readFileSync(reportPath, "utf8") !== report) {
    errors.push(`${reportPath} is stale. Run npm run licenses.`);
  }
  return errors;
}
